#!/bin/bash

# 1. Обробка кліку мишки (BLOCK_BUTTON=1 — це лівий клік)
if [ "$BLOCK_BUTTON" -eq 1 ]; then
  baobab / &
fi

# 2. Отримуємо вільне місце в мегабайтах (для точного порівняння)
FREE_MB=$(df -m / | awk 'NR==2 {print $4}')

# 3. Виводимо текст для бару (наприклад, 18G)
df -h / | awk 'NR==2 {print $4}'

# 4. Виводимо короткий текст (вимагається i3blocks)
df -h / | awk 'NR==2 {print $4}'

# 5. Динамічно міняємо колір (якщо менше 25 ГБ = 25600 МБ)
if [ "$FREE_MB" -lt 25600 ]; then
  echo "#E74C3C" # Червоний
else
  echo "#2ECC71" # Зелений
fi
